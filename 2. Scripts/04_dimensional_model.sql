CREATE SCHEMA IF NOT EXISTS FLEETLOGIX_DW.ANALYTICS;

CREATE SEQUENCE IF NOT EXISTS FLEETLOGIX_DW.ANALYTICS.SEQ_DRIVER_VERSION start with 1000000 increment by 1 noorder;
CREATE TABLE IF NOT EXISTS FLEETLOGIX_DW.ANALYTICS.AGG_ENTREGAS_HORA (
	DATE_KEY NUMBER(38,0),
	TIME_KEY NUMBER(38,0),
	DRIVER_KEY NUMBER(38,0),
	TOTAL_ENTREGAS NUMBER(18,0),
	DURACION_PROMEDIO_MIN NUMBER(31,2),
	DISTANCIA_TOTAL_KM NUMBER(24,2),
	COMBUSTIBLE_TOTAL_L NUMBER(24,3)
);
CREATE TABLE IF NOT EXISTS FLEETLOGIX_DW.ANALYTICS.DIM_CUSTOMER (
	CUSTOMER_KEY VARCHAR(64) NOT NULL,
	CUSTOMER_NAME VARCHAR(200),
	DELIVERY_ADDRESS VARCHAR(1000),
	primary key (CUSTOMER_KEY)
);
CREATE TABLE IF NOT EXISTS FLEETLOGIX_DW.ANALYTICS.DIM_DATE (
	DATE_KEY NUMBER(8,0) NOT NULL,
	FULL_DATE DATE,
	YEAR NUMBER(38,0),
	QUARTER NUMBER(38,0),
	MONTH NUMBER(38,0),
	MONTH_NAME VARCHAR(20),
	DAY_OF_MONTH NUMBER(38,0),
	DAY_OF_WEEK NUMBER(38,0),
	IS_WEEKEND BOOLEAN,
	IS_HOLIDAY BOOLEAN,
	primary key (DATE_KEY)
);
CREATE TABLE IF NOT EXISTS FLEETLOGIX_DW.ANALYTICS.DIM_DRIVER (
	DRIVER_KEY NUMBER(38,0) NOT NULL,
	DRIVER_ID NUMBER(38,0),
	EMPLOYEE_CODE VARCHAR(20),
	FULL_NAME VARCHAR(200),
	LICENSE_EXPIRY DATE,
	HIRE_DATE DATE,
	STATUS VARCHAR(20),
	VALID_FROM TIMESTAMP_NTZ(9),
	VALID_TO TIMESTAMP_NTZ(9),
	IS_CURRENT BOOLEAN,
	primary key (DRIVER_KEY)
);
CREATE TABLE IF NOT EXISTS FLEETLOGIX_DW.ANALYTICS.DIM_ROUTE (
	ROUTE_KEY NUMBER(38,0) NOT NULL,
	ROUTE_ID NUMBER(38,0),
	ROUTE_CODE VARCHAR(20),
	ORIGIN_CITY VARCHAR(100),
	DESTINATION_CITY VARCHAR(100),
	DISTANCE_KM NUMBER(10,2),
	ESTIMATED_DURATION_HOURS NUMBER(5,2),
	TOLL_COST NUMBER(10,2),
	primary key (ROUTE_KEY)
);
CREATE TABLE IF NOT EXISTS FLEETLOGIX_DW.ANALYTICS.DIM_TIME (
	TIME_KEY NUMBER(38,0) NOT NULL,
	HOUR NUMBER(38,0),
	MINUTE NUMBER(38,0),
	SECOND NUMBER(38,0),
	SHIFT_NAME VARCHAR(20),
	primary key (TIME_KEY)
);
CREATE TABLE IF NOT EXISTS FLEETLOGIX_DW.ANALYTICS.DIM_VEHICLE (
	VEHICLE_KEY NUMBER(38,0) NOT NULL,
	VEHICLE_ID NUMBER(38,0),
	LICENSE_PLATE VARCHAR(20),
	VEHICLE_TYPE VARCHAR(50),
	CAPACITY_KG NUMBER(10,2),
	FUEL_TYPE VARCHAR(20),
	ACQUISITION_DATE DATE,
	STATUS VARCHAR(20),
	primary key (VEHICLE_KEY)
);
CREATE TABLE IF NOT EXISTS FLEETLOGIX_DW.ANALYTICS.FACT_DELIVERIES (
	DELIVERY_ID NUMBER(38,0) NOT NULL,
	TRIP_ID NUMBER(38,0),
	DATE_KEY NUMBER(38,0),
	TIME_KEY NUMBER(38,0),
	VEHICLE_KEY NUMBER(38,0),
	DRIVER_KEY NUMBER(38,0),
	ROUTE_KEY NUMBER(38,0),
	CUSTOMER_KEY VARCHAR(64),
	SCHEDULED_DATETIME TIMESTAMP_NTZ(9),
	DELIVERED_DATETIME TIMESTAMP_NTZ(9),
	DELIVERY_DURATION_MINUTES NUMBER(12,2),
	DISTANCE_KM NUMBER(12,2),
	FUEL_CONSUMED_LITERS NUMBER(12,3),
	PACKAGE_WEIGHT_KG NUMBER(10,2),
	REVENUE_ESTIMATED NUMBER(12,2),
	IS_ON_TIME BOOLEAN,
	LOAD_TIMESTAMP TIMESTAMP_NTZ(9) DEFAULT CURRENT_TIMESTAMP(),
	primary key (DELIVERY_ID)
);
CREATE TABLE IF NOT EXISTS FLEETLOGIX_DW.ANALYTICS.STG_DRIVER_SNAPSHOT (
	DRIVER_ID NUMBER(38,0),
	EMPLOYEE_CODE VARCHAR(20),
	FULL_NAME VARCHAR(200),
	LICENSE_EXPIRY DATE,
	HIRE_DATE DATE,
	STATUS VARCHAR(20),
	EXTRACTED_AT TIMESTAMP_NTZ(9) DEFAULT CURRENT_TIMESTAMP()
);
CREATE SECURE VIEW IF NOT EXISTS FLEETLOGIX_DW.ANALYTICS.VW_OPERACIONES(
	DELIVERY_ID,
	TRIP_ID,
	DATE_KEY,
	TIME_KEY,
	VEHICLE_KEY,
	DRIVER_KEY,
	ROUTE_KEY,
	CUSTOMER_KEY,
	SCHEDULED_DATETIME,
	DELIVERED_DATETIME,
	DELIVERY_DURATION_MINUTES,
	DISTANCE_KM,
	FUEL_CONSUMED_LITERS,
	PACKAGE_WEIGHT_KG,
	REVENUE_ESTIMATED,
	IS_ON_TIME,
	LOAD_TIMESTAMP
) as
SELECT *
FROM FLEETLOGIX_DW.ANALYTICS.FACT_DELIVERIES;
CREATE SECURE VIEW IF NOT EXISTS FLEETLOGIX_DW.ANALYTICS.VW_VENTAS(
	DATE_KEY,
	ROUTE_KEY,
	TOTAL_ENTREGAS,
	INGRESOS_ESTIMADOS
) as
SELECT
    DATE_KEY,
    ROUTE_KEY,
    COUNT(*) AS TOTAL_ENTREGAS,
    SUM(REVENUE_ESTIMATED) AS INGRESOS_ESTIMADOS
FROM FLEETLOGIX_DW.ANALYTICS.FACT_DELIVERIES
GROUP BY DATE_KEY, ROUTE_KEY;
CREATE OR REPLACE PROCEDURE FLEETLOGIX_DW.ANALYTICS.SP_REFRESH_AGGREGATES()
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS '
BEGIN
    CREATE OR REPLACE TABLE
    FLEETLOGIX_DW.ANALYTICS.AGG_ENTREGAS_HORA
    COPY GRANTS AS
    SELECT
        DATE_KEY,
        TIME_KEY,
        DRIVER_KEY,
        COUNT(*) AS TOTAL_ENTREGAS,
        ROUND(AVG(DELIVERY_DURATION_MINUTES), 2)
            AS DURACION_PROMEDIO_MIN,
        ROUND(SUM(DISTANCE_KM), 2)
            AS DISTANCIA_TOTAL_KM,
        ROUND(SUM(FUEL_CONSUMED_LITERS), 3)
            AS COMBUSTIBLE_TOTAL_L
    FROM FLEETLOGIX_DW.ANALYTICS.FACT_DELIVERIES
    GROUP BY DATE_KEY, TIME_KEY, DRIVER_KEY;

    RETURN ''Metricas actualizadas correctamente'';
END;
';
